import { Joi } from "celebrate";

// Єдине джерело правди для формату email у проєкті. До цього register мав
// власну регулярку, а login і updateUser — Joi.string().email() (звіряє
// TLD зі списком IANA, суворіше). Хтось реєструвався з поштою в нестандартній
// зоні (напр. mail.local) і назавжди не міг залогінитись — 400 там, де
// register її прийняв. Три копії того самого правила розійшлися одного разу
// вже — тому тепер правило одне, і його імпортують, а не копіюють.
export const emailSchema = () =>
  Joi.string()
    .trim()
    .lowercase()
    .max(64)
    .pattern(/^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$/);
